USE CURSO;

-- EJERCICIO 1

SELECT CLIENTE_NO, NOMBRE
FROM CLIENTES
WHERE VENDEDOR_NO = (SELECT EMP_NO
		     FROM EMPLEADOS
		     WHERE APELLIDO = 'CALVO');

-- EJERCICIO 2

SELECT PEDIDO_NO, PRODUCTO_NO, FECHA_PEDIDO
FROM PEDIDOS
WHERE CLIENTE_NO = (SELECT CLIENTE_NO
		    FROM CLIENTES
		    WHERE NOMBRE = 'EDICIONES SANZ');
		    
-- EJERCICIO 3

SELECT CLIENTE_NO, NOMBRE, LIMITE_CREDITO
FROM CLIENTES
WHERE LIMITE_CREDITO > (SELECT LIMITE_CREDITO
			FROM CLIENTES
			GROUP BY LIMITE_CREDITO
			HAVING AVG(LIMITE_CREDITO)
			LIMIT 1);

-- EJERCICIO 4

SELECT *
FROM PRODUCTOS
WHERE PRECIO_ACTUAL = (SELECT PRECIO_ACTUAL
		       FROM PRODUCTOS
		       GROUP BY PRECIO_ACTUAL
		       HAVING MAX(PRECIO_ACTUAL)
		       LIMIT 1);
		       
-- EJERCICIO 5

SELECT NOMBRE, CLIENTE_NO
FROM CLIENTES
WHERE CLIENTE_NO IN (SELECT CLIENTE_NO
		    FROM PEDIDOS
		    WHERE PRODUCTO_NO = (SELECT PRODUCTO_NO
					 FROM PRODUCTOS
					 WHERE DESCRIPCION = 'DESTRUCTORA DE PAPEL A3'));

-- EJERCICIO 6

SELECT APELLIDO, OFICIO
FROM EMPLEADOS
WHERE EMP_NO IN (SELECT VENDEDOR_NO
		 FROM CLIENTES
		 GROUP BY VENDEDOR_NO
		 HAVING COUNT(*) > 2);
		     
