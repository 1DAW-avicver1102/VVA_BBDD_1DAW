-- EJERCICIO 8

SELECT *
FROM EMPLEADOS
WHERE EMP_NO IN (SELECT VENDEDOR_NO
		 FROM CLIENTES
		 WHERE CLIENTE_NO NOT IN (SELECT DISTINCT CLIENTE_NO
				     FROM PEDIDOS));

-- EJERCICIO 9

SELECT DNOMBRE
FROM DEPARTAMENTOS
WHERE DEP_NO IN (SELECT DEP_NO
		FROM EMPLEADOS
		WHERE EMP_NO IN (SELECT EMP_NO
				FROM EMPLEADOS
				GROUP BY EMP_NO
				HAVING MAX(SALARIO)));
				
-- EJERCICIO 10

SELECT APELLIDO, EMP_NO
FROM EMPLEADOS emp1
WHERE SALARIO < (SELECT AVG(SALARIO)
		 FROM EMPLEADOS
		 WHERE emp1.DEP_NO = DEP_NO);
		 
-- EJERCICIO 11

SELECT NOMBRE, LOCALIDAD
FROM CLIENTES
WHERE CLIENTE_NO IN (SELECT CLIENTE_NO
		     FROM PEDIDOS
		     WHERE CLIENTE_NO IN (SELECT DISTINCT CLIENTE_NO
					  FROM PEDIDOS));
					  
-- EJERCICIO 12

SELECT DNOMBRE
FROM DEPARTAMENTOS
WHERE DEP_NO = (SELECT DEP_NO
		FROM EMPLEADOS
		GROUP BY DEP_NO 
		ORDER BY MIN(SALARIO+IFNULL(COMISION, 0)) ASC
		LIMIT 1);

