-- EJERCICIO 6

SELECT EMP_NO, APELLIDO, COMISION
FROM EMPLEADOS
WHERE IFNULL(COMISION,0) = (SELECT IFNULL(COMISION,0)
		  FROM EMPLEADOS
		  GROUP BY COMISION
		  HAVING AVG(SALARIO)
		  LIMIT 1);
