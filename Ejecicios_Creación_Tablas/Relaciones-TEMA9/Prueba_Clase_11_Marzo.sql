-- EJERCICIO 20

SELECT DISTINCT *
FROM EMPLEADOS
WHERE (DIRECTOR, DEP_NO) = (SELECT DIRECTOR, DEP_NO
			    FROM EMPLEADOS
			    WHERE APELLIDO = 'ALONSO')

GROUP BY EMP_NO
HAVING APELLIDO <> 'ALONSO';

-- EJERCICIO 21

