FROM DEPARTAMENTOS
WHERE DEP_NO IN (SELECT DEP_NO
		FROM EMPLEADOS
		GROUP BY DEP_NO 
		HAVING AVG(SALARIO) >= (SELECT AVG(SALARIO)
				       FROM EMPLEADOS));
				       
-- EJERCICIO 22

