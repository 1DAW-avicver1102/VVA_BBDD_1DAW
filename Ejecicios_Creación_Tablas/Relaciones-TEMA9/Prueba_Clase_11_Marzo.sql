-- EJERCICIO 6

SELECT COUNT(*) AS Num_empleados
FROM EMPLEADOS
WHERE OFICIO = 'VENDEDOR'
AND DEP_NO = (SELECT DEP_NO
	      FROM DEPARTAMENTOS
	      WHERE DNOMBRE = 'VENTAS');

-- EJERCICIO 7

SELECT OFICIO, SUM(SALARIO) AS Suma_salario
FROM EMPLEADOS	
WHERE DEP_NO = (SELECT DEP_NO
		FROM DEPARTAMENTOS
		WHERE DNOMBRE = 'VENTAS')
GROUP BY OFICIO;

-- EJERCICIO 8

SELECT *
FROM EMPLEADOS
WHERE EMP_NO IN (SELECT EMP_NO
		 FROM EMPLEADOS
		 WHERE DEP_NO NOT IN (SELECT DEP_NO
					  FROM DEPARTAMENTOS
					  WHERE LOCALIDAD = 'MADRID'
					  OR LOCALIDAD = 'BARCELONA'));

